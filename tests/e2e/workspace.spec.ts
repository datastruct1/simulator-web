test('冷热水急停关闭两泵六阀并锁面板，复位不启动泵也不清除设备故障', async ({ page }) => {
  await teacher(page)
  await page.evaluate(() => {
    const simulator = (window as any).__testSimulator
    for (const id of ['P401', 'P402', 'H1401', 'H1402', 'H1403', 'H1404', 'H1405', 'H1406']) simulator.setDevice(id, { value: 100, working: true })
  })
  await page.locator('[data-page="water"]').click()
  await page.locator('[data-node-id="water-button-5"]').click()
  let result = await page.evaluate(() => {
    const devices = (window as any).__testSimulator.state.devices
    return { panel: devices.WaterControlPanel.enabled, states: ['P401', 'P402', 'H1401', 'H1402', 'H1403', 'H1404', 'H1405', 'H1406'].map(id => [devices[id].value, devices[id].working]) }
  })
  expect(result.panel).toBe(false)
  expect(result.states.every(([value, working]) => value === 0 && !working)).toBe(true)
  await expect(page.locator('[data-node-id="water-button-1"]')).toBeDisabled()
  await page.locator('[data-node-id="water-button-1"]').click({ force: true })
  expect(await page.evaluate(() => (window as any).__testSimulator.state.devices.P401.working)).toBe(false)
  await page.evaluate(() => (window as any).__testSimulator.setDevice('P401', { error: true }))
  await page.locator('[data-node-id="water-button-6"]').click()
  const reset = await page.evaluate(() => {
    const devices = (window as any).__testSimulator.state.devices
    return { panel: devices.WaterControlPanel.enabled, mainWorking: devices.P401.working, backupWorking: devices.P402.working, fault: devices.P401.error }
  })
  expect(reset).toEqual({ panel: true, mainWorking: false, backupWorking: false, fault: true })
})

