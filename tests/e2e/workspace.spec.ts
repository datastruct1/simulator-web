import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

// Test-only access to the already loaded module URLs: importing a cache-busted
// second copy of the state module would test the wrong singleton.
async function runtime(page: Page) {
  await page.evaluate(async () => {
    const resources = performance.getEntriesByType('resource')
    const simulator = resources.find(item => item.name.includes('/src/state/simulator.ts'))
    const workspace = resources.find(item => item.name.includes('/src/state/workspace.ts'))
    if (!simulator || !workspace) throw new Error('Shared runtime modules were not loaded')
    ;(window as any).__testSimulator = (await import(simulator.name)).useSimulator()
    ;(window as any).__testWorkspace = (await import(workspace.name)).useWorkspace()
  })
}
async function teacher(page: Page) {
  await page.goto('/?demo=1')
  await expect(page.getByTestId('wpf-scene')).toBeVisible()
  await runtime(page)
}
async function student(page: Page) {
  await page.getByRole('button', { name: '学员登录', exact: true }).click()
  await page.getByRole('button', { name: '无需填写信息，体验演示学员', exact: true }).click()
  await expect(page.getByTestId('student-workspace')).toBeVisible()
  await runtime(page)
}
async function openEditor(page: Page) {
  await page.getByTestId('more-tools').click()
  await page.getByRole('button', { name: '场景编辑器', exact: true }).click()
  await expect(page.getByTestId('scene-editor')).toBeVisible()
}
async function applyValve(page: Page, value = '75%') {
  await page.locator('[data-runtime-device-id="V1601"][data-node-kind="valve"]').first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: value, exact: true }).click()
  await dialog.getByRole('button', { name: '应用', exact: true }).click()
  await dialog.getByRole('button', { name: '关闭窗口', exact: true }).click()
}

