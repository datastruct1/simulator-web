test('活动告警播放原本地警报音，消音、确认和退出会停止播放', async ({ page }) => {
  await page.addInitScript(() => {
    const original = HTMLMediaElement.prototype.play
    HTMLMediaElement.prototype.play = function () {
      if (this.src.includes('/assets/sounds/warning1.wav')) (window as any).__testAlarmAudio = this
      return original.call(this)
    }
  })
  await teacher(page)
  await page.evaluate(() => (window as any).__testSimulator.injectFault('P101', '浏览器警报音测试'))
  await page.locator('button[title="返回首页"]').click()
  await expect.poll(() => page.evaluate(() => (window as any).__testAlarmAudio?.paused)).toBe(false)
  await page.locator('button[title="消音"]').click()
  await expect.poll(() => page.evaluate(() => (window as any).__testAlarmAudio?.paused)).toBe(true)
  await page.locator('button[title="取消消音"]').click()
  await expect.poll(() => page.evaluate(() => (window as any).__testAlarmAudio?.paused)).toBe(false)
  await page.evaluate(() => { const simulator = (window as any).__testSimulator; for (const alarm of simulator.activeAlarms.value) simulator.acknowledgeAlarm(alarm.id) })
  await expect.poll(() => page.evaluate(() => (window as any).__testAlarmAudio?.paused)).toBe(true)
  await page.evaluate(() => (window as any).__testSimulator.injectFault('P402', '退出停止声音测试'))
  await page.locator('button[title="返回首页"]').click()
  await expect.poll(() => page.evaluate(() => (window as any).__testAlarmAudio?.paused)).toBe(false)
  await page.locator('button[title="退出系统"]').click()
  await page.getByRole('dialog').getByRole('button', { name: '退出系统', exact: true }).click()
  await expect(page.getByText('系统登录', { exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => (window as any).__testAlarmAudio?.paused)).toBe(true)
})
